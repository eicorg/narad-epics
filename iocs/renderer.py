from __future__ import annotations

import os
import tempfile
from collections.abc import Sequence
from pathlib import Path

from .models import EpicsRecord


def render_database(records: Sequence[EpicsRecord], *, source: Path) -> str:
    lines = [f"# Generated by narad-epics from {source.name}", ""]
    for record_index, record in enumerate(records):
        lines.append(
            f'record({record.record_type}, "{_escape(record.name)}") {{'
        )
        for alias in record.aliases:
            lines.append(f'    alias("{_escape(alias)}")')
        for name, value in record.info_items:
            lines.append(f'    info({name}, "{_escape(value)}")')
        for name, value in record.fields:
            lines.append(f'    field({name}, "{_escape(value)}")')
        lines.append("}")
        if record_index < len(records) - 1:
            lines.append("")
    return "\n".join(lines) + "\n"


def write_database(path: str | Path, content: str) -> Path:
    destination = Path(path).resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            prefix=f".{destination.name}.",
            suffix=".tmp",
            dir=destination.parent,
            delete=False,
        ) as temporary_file:
            temporary_file.write(content)
            temporary_path = Path(temporary_file.name)
        os.replace(temporary_path, destination)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()
    return destination


def _escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')