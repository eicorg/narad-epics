class GenerationTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary_directory.cleanup)
        self.root = Path(self.temporary_directory.name)
        self.source = self.root / "description.yaml"
        self.source.write_text(textwrap.dedent(DESCRIPTION), encoding="utf-8")

    def test_maps_signals_and_groups_binding_aliases_in_source_order(self) -> None:
        description = load_narad_description(self.source)

        records = map_description(description)

        self.assertEqual([record.record_type for record in records], ["ai", "ao", "stringin"])
        bpm = records[0]
        self.assertEqual(bpm.name, "inst:bpm1:X-RB")
        self.assertEqual(
            bpm.aliases,
            (
                "inst:BPM1:horizontal_position_binding",
                "inst:BPM1:secondary_position_binding",
            ),
        )
        self.assertEqual(
            bpm.info_items,
            (
                ("naradBindingId0", "inst:BPM1.horizontal_position_binding"),
                ("naradBindingId1", "inst:BPM1.secondary_position_binding"),
            ),
        )
        self.assertEqual(
            bpm.fields,
          (
            ("DESC", "Measured horizontal beam position."),
            ("EGU", "mm"),
            ("PREC", "3"),
            ("VAL", "0"),
            ("UDF", "0"),
          ),
        )
        self.assertEqual(
          records[1].fields[0],
          ("DESC", "Desired magnet current command with extr"),
        )
        self.assertEqual(
          records[2].fields,
          (
            ("DESC", 'Power supply "state" summary.'),
            ("VAL", "UNKNOWN"),
            ("UDF", "0"),
          ),
        )

    def test_renders_stable_epics_database_syntax_and_escapes_strings(self) -> None:
        records = map_description(load_narad_description(self.source))

        rendered = render_database(records, source=self.source)

        self.assertTrue(rendered.startswith("# Generated by narad-epics from description.yaml\n"))
        self.assertIn('record(ai, "inst:bpm1:X-RB") {', rendered)
        self.assertIn('    alias("inst:BPM1:horizontal_position_binding")', rendered)
        self.assertIn(
            '    info(naradBindingId0, "inst:BPM1.horizontal_position_binding")',
            rendered,
        )
        self.assertIn('    field(EGU, "mm")', rendered)
        self.assertIn('    field(VAL, "0")', rendered)
        self.assertIn('    field(VAL, "UNKNOWN")', rendered)
        self.assertIn('    field(UDF, "0")', rendered)
        self.assertIn('    field(DESC, "Power supply \\"state\\" summary.")', rendered)
        self.assertNotIn("field(EGU, \"none\")", rendered)
        self.assertTrue(rendered.endswith("}\n"))

    def test_cli_check_validates_without_writing_a_database(self) -> None:
        output = io.StringIO()

        with contextlib.redirect_stdout(output):
            exit_code = main([str(self.source), "--check"])

        self.assertEqual(exit_code, 0)
        self.assertIn("3 signals, 4 bindings, 3 records", output.getvalue())
        self.assertEqual(list(self.root.glob("*.db")), [])

    def test_cli_generates_database_file(self) -> None:
        destination = self.root / "generated" / "records.db"
        output = io.StringIO()

        with contextlib.redirect_stdout(output):
            exit_code = main([str(self.source), "--output", str(destination)])

        self.assertEqual(exit_code, 0)
        self.assertTrue(destination.is_file())
        self.assertIn('record(ao, "inst:t1:PS:H:Current-SP")', destination.read_text())
        self.assertIn(str(destination), output.getvalue())


if __name__ == "__main__":
    unittest.main()